# Generates the build inputs that build.bat compiles into the DLL:
#   build\helper_gsc.inc  the compiled GSC helper (scripts\t6gnosis_helper.gsc) as a
#                         byte list; the DLL writes it to Plutonium's scripts\zm at startup.
#   build\version.inc     the version (GNOSIS_VERSION, "dev" unless -Version is given)
#                         and its numbers for the DLL's version resource.
# The GSC compiler is xensik's gsc-tool: -GscTool, else %GSC_TOOL%, else
# tools\gsc-tool.exe in this repository, else gsc-tool.exe one folder up.
param(
    [string]$GscTool = '',
    [string]$Version = ''
)
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$build = Join-Path $root 'build'
$candidates = @($GscTool, $env:GSC_TOOL, (Join-Path $root 'tools\gsc-tool.exe'), (Join-Path (Split-Path $root -Parent) 'gsc-tool.exe'))
$compiler = $candidates | Where-Object { $_ -and (Test-Path -LiteralPath $_ -PathType Leaf) } | Select-Object -First 1
if (-not $compiler) { throw 'gsc-tool.exe not found: pass -GscTool, set GSC_TOOL, or place it in tools\.' }

# Compile in a private folder: gsc-tool writes compiled\t6\<name> under the working folder.
$stage = Join-Path $build 'helper'
if (Test-Path -LiteralPath $stage) { Remove-Item -LiteralPath $stage -Recurse -Force }
New-Item -ItemType Directory -Path $stage -Force | Out-Null
Copy-Item -LiteralPath (Join-Path $root 'scripts\t6gnosis_helper.gsc') -Destination $stage
Push-Location -LiteralPath $stage
try {
    $output = @(& $compiler -m comp -g t6 -s pc -i server 't6gnosis_helper.gsc' 2>&1)
    $exit = $LASTEXITCODE
} finally { Pop-Location }
$compiled = Join-Path $stage 'compiled\t6\t6gnosis_helper.gsc'
if ($exit -ne 0 -or -not (Test-Path -LiteralPath $compiled -PathType Leaf)) {
    $output | ForEach-Object { Write-Host $_ }
    throw 'GSC helper compilation failed.'
}
$bytes = [IO.File]::ReadAllBytes($compiled)
if ($bytes.Length -le 0) { throw 'Compiled GSC helper is empty.' }
$text = New-Object System.Text.StringBuilder
[void]$text.AppendLine('// Generated by generate.ps1 from scripts\t6gnosis_helper.gsc; do not edit.')
for ($i = 0; $i -lt $bytes.Length; $i++) {
    [void]$text.Append('0x').Append($bytes[$i].ToString('X2')).Append(',')
    if (($i % 32) -eq 31) { [void]$text.AppendLine() }
}
[void]$text.AppendLine()
$utf8 = New-Object System.Text.UTF8Encoding $false
[IO.File]::WriteAllText((Join-Path $build 'helper_gsc.inc'), $text.ToString(), $utf8)
Write-Host ("GSC helper compiled and embedded ({0} bytes)." -f $bytes.Length)

# Always written: the DLL's version resource (src\T6Gnosis.rc) needs it too.
if (-not $Version) { $Version = 'dev' }
if ($Version -notmatch '^[0-9A-Za-z.\-]+$') { throw "Invalid version: $Version" }
$numbers = @(([regex]::Matches($Version, '\d+') | Select-Object -First 4 | ForEach-Object { [int]$_.Value }))
while ($numbers.Count -lt 4) { $numbers += 0 }
$lines = "#define GNOSIS_VERSION `"$Version`"`r`n#define GNOSIS_VERSION_NUMBERS $($numbers -join ',')`r`n"
[IO.File]::WriteAllText((Join-Path $build 'version.inc'), $lines, $utf8)
Write-Host "Version $Version."
